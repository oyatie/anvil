#[test]
fn every_locked_package_is_resolved_with_its_exact_version() {
    let pkgs = packages();
    assert_eq!(pkgs.len(), 3, "three [[package]] tables, three packages");
    assert_eq!(pkgs[1].name, "time");
    assert_eq!(
        pkgs[1].version, "0.1.44",
        "the exact locked version is what an advisory range is matched against; \
         a requirement from Cargo.toml is not"
    );
}

#[test]
fn a_malformed_lockfile_is_an_error_not_an_empty_package_list() {
    // An empty Vec would sail through the whole gate as "nothing vulnerable",
    // which is precisely how `vec![]` made the zero-day gate unfailable.
    let err = SupplyChainGuard::parse_lockfile("[[package]\nname = ")
        .expect_err("a truncated TOML table is not a lockfile");
    assert!(
        !err.trim().is_empty(),
        "the parse failure must carry a reason a reader can act on"
    );
}

#[test]
fn a_lockfile_with_no_packages_is_an_error_not_a_clean_audit() {
    let err = SupplyChainGuard::parse_lockfile("version = 4\n")
        .expect_err("a lockfile listing nothing audits nothing");
    assert!(err.to_lowercase().contains("package"));
}

