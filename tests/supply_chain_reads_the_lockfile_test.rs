#[test]
fn the_batch_payload_asks_about_every_locked_package_by_name_and_version() {
    let payload = OsvAdvisoryStream::build_batch_payload(&packages());
    let json: serde_json::Value = serde_json::from_str(&payload).expect("payload is JSON");
    let queries = json["queries"].as_array().expect("queries array");

    assert_eq!(
        queries.len(),
        3,
        "one query per locked package; a batch shorter than the lockfile leaves \
         packages unaudited while reporting on the ones it did send"
    );
    assert_eq!(queries[1]["package"]["name"], "time");
    assert_eq!(queries[1]["version"], "0.1.44");
    assert_eq!(
        queries[1]["package"]["ecosystem"], "crates.io",
        "OSV keys Rust advisories under the crates.io ecosystem; any other \
         string matches nothing and returns an empty, reassuring result"
    );
}

#[test]
fn an_advisory_against_a_locked_version_is_attributed_to_that_package() {
    let hits = OsvAdvisoryStream::parse_batch_response(BATCH_HIT, &packages())
        .expect("a well-formed batch response parses");

    assert_eq!(
        hits.len(),
        1,
        "one of the three packages carries advisories"
    );
    assert_eq!(hits[0].name, "time");
    assert_eq!(hits[0].version, "0.1.44");
    assert_eq!(
        hits[0].advisory_ids,
        vec!["RUSTSEC-2020-0071", "GHSA-wcg3-cvx6-7396"],
        "every advisory id is carried through, so the scorecard names what to fix"
    );
}

#[test]
fn a_response_clean_for_every_package_finds_nothing() {
    let hits = OsvAdvisoryStream::parse_batch_response(BATCH_CLEAN, &packages())
        .expect("a clean batch response parses");
    assert!(hits.is_empty());
}

#[test]
fn a_response_body_that_is_not_json_is_an_error_not_a_clean_audit() {
    // A proxy interstitial, an HTML error page, or a truncated body. Every one
    // of them deserialises to "no vulns" if the failure is swallowed.
    for body in ["", "<html>502 Bad Gateway</html>", "{\"results\":"] {
        assert!(
            OsvAdvisoryStream::parse_batch_response(body, &packages()).is_err(),
            "body {body:?} must not parse as an advisory-free result"
        );
    }
}

#[test]
fn a_result_list_shorter_than_the_query_list_is_an_error() {
    // OSV pairs results to queries positionally. A short list silently shifts
    // every advisory onto the wrong package, and clears the tail.
    let err = OsvAdvisoryStream::parse_batch_response(r#"{"results":[{},{}]}"#, &packages())
        .expect_err("two results cannot answer three queries");
    assert!(
        err.contains('2') && err.contains('3'),
        "the error must state both counts so the mismatch is legible: {err}"
    );
}

/// Catches: a truncated advisory list published as though it were the answer.
/// OSV paginates a batch result past its own vulnerability thresholds and hands
/// back a `next_page_token`. Deserialising only `vulns` dropped it silently, so
/// the gate would name the first page of advisories and nothing would say the
/// rest existed -- on a gate whose entire value is naming what to fix.
#[test]
fn a_paginated_batch_is_an_error_not_a_shorter_advisory_list() {
    let body = r#"{"results":[{"vulns":[{"id":"RUSTSEC-2020-0071"}],
                   "next_page_token":"ct1"},{},{}]}"#;
    let err = OsvAdvisoryStream::parse_batch_response(body, &packages())
        .expect_err("a paginated result cannot be read as the complete answer");
    assert!(
        err.contains("incomplete"),
        "the error must say the advisory list is incomplete: {err}"
    );
}

/// Catches: the abstention above swallowing the ordinary case. Every clean and
/// every complete result carries no token, and those must still parse.
#[test]
fn an_unpaginated_batch_still_parses() {
    let body = r#"{"results":[{"vulns":[{"id":"RUSTSEC-2020-0071"}]},{},{}]}"#;
    let found = OsvAdvisoryStream::parse_batch_response(body, &packages())
        .expect("a complete batch parses");
    assert_eq!(found.len(), 1);
}

