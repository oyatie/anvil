#[test]
fn a_lockfile_carrying_an_advisory_fails_the_gate() {
    let pkgs = packages();
    let hits = OsvAdvisoryStream::parse_batch_response(BATCH_HIT, &pkgs).expect("parses");
    let report = SupplyChainGuard::report(&pkgs, Ok(hits));

    let GateStatus::Failed(reason) = &report.status else {
        panic!("a locked version with a live advisory must fail: {report:?}");
    };
    assert!(
        reason.contains("time")
            && reason.contains("0.1.44")
            && reason.contains("RUSTSEC-2020-0071"),
        "the failure must name the package, the locked version and the advisory: {reason}"
    );
    assert_eq!(report.audited_packages, 3);
}

#[test]
fn a_clean_lockfile_passes_the_gate() {
    let pkgs = packages();
    let report = SupplyChainGuard::report(&pkgs, Ok(Vec::new()));

    assert!(
        matches!(report.status, GateStatus::Passed),
        "a resolved lockfile with no advisory against any locked version is a \
         measured pass, not an abstention: {report:?}"
    );
    assert_eq!(
        report.audited_packages, 3,
        "the count published is the number of packages queried, not the number \
         of files the pull request touched"
    );
}

#[test]
fn an_unreachable_advisory_database_is_not_measured_and_never_a_pass() {
    let report = SupplyChainGuard::report(&packages(), Err("curl exited 6".to_string()));

    assert_not_measured(&report.status, "supply_chain_status", &["curl exited 6"]);
    assert!(
        !report.status.is_measured(),
        "an absent advisory feed blocks admission through unmeasured_gates; it \
         must not be laundered into a pass"
    );
}

