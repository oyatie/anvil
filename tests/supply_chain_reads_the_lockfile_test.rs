//! Lane `supply-chain-reads-the-lockfile`: two gates that claimed to audit a
//! dependency graph and never opened one.
//!
//! # The defect, restated from source
//!
//! `zero_day_status` publishes "Autonomous upstream RustSec/CVE patch
//! synthesis". Its evaluation was
//!
//!     let active_advisories = vec![];
//!     let detected = self.listener.reconcile_advisories(&diff_ctx.diff_content, &active_advisories);
//!     let is_clean = detected.is_empty();
//!
//! An empty advisory list makes the loop inside `reconcile_advisories` execute
//! zero times, so `detected` is empty on every input and `is_clean` is `true`
//! on every pull request. The same shape as the two literals fixed in #63,
//! spelled `vec![]` instead of `true`. It also never read a lockfile: the
//! matcher's parameter is named `lockfile_content` and the caller handed it
//! `diff_ctx.diff_content`. Nothing in the module writes a patch, so the
//! "synthesis" half has no implementation at all and the gate now abstains.
//!
//! `supply_chain_status` publishes "Dependency audit, Syft CycloneDX SBOM &
//! provenance". It text-scanned the diff for six package names. No lockfile, no
//! advisory database, no SBOM, and `slsa_provenance_generated` was assigned
//! `is_secure` -- a self-attested SLSA level, which the SLSA build track does
//! not permit at L2 in any case (the hosted platform must be the signer).
//!
//! # What replaces it
//!
//! `SupplyChainGuard::audit_supply_chain` reads `Cargo.lock` from the working
//! tree, resolves every `[[package]]` entry, and queries OSV.dev's
//! `/v1/querybatch` endpoint -- the same database `osv-scanner` uses -- through
//! the bounded executor. A real advisory against a real locked version fails
//! the gate; every way the query can fail reports `NotMeasured`.
//!
//! # Why every test here is offline
//!
//! A gate whose test suite reaches api.osv.dev is a gate whose test suite is a
//! network monitor. The transport is one function, `post_json`, and it is
//! exercised against programs that are not curl. Everything that decides a
//! verdict -- lockfile parsing, payload construction, response parsing, the
//! pass/fail rule -- is pure and is driven from fixtures.

use anvil::git_manager::PrDiffContext;
use anvil::pre_merge_guard::report::GateStatus;
use anvil::supply_chain_guard::osv_stream::{self, OsvAdvisoryStream};
use anvil::supply_chain_guard::{LockedPackage, SupplyChainGuard};
use anvil::zero_day_patcher::ZeroDayAutoPatcher;
use std::path::Path;
use std::time::Duration;

