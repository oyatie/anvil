#[test]
fn the_zero_day_gate_abstains_on_a_diff_that_would_previously_have_passed() {
    // The old evaluation was `vec![]` -> `detected.is_empty()` -> `is_clean`,
    // so a diff introducing a known-vulnerable version was certified clean.
    // Nothing about the diff may produce a pass now.
    let work = tempfile::tempdir().expect("tempdir");
    let mut d = ctx(work.path());
    d.diff_content = "+time = \"0.1.44\"\n+openssl = \"0.10.30\"\n".to_string();

    let report = ZeroDayAutoPatcher::new()
        .evaluate_zero_day_patches(work.path(), &d)
        .expect("the gate answers");

    assert!(
        !report.status.is_measured(),
        "the zero-day gate reads no advisory feed and writes no patch; a diff \
         cannot make it pass: {report:?}"
    );
}

