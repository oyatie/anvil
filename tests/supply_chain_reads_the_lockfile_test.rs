/// A minimal but real `Cargo.lock`, v4, three packages.
const LOCKFILE: &str = r#"
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "anvil"
version = "0.1.0"
dependencies = ["time"]

[[package]]
name = "time"
version = "0.1.44"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "6db9e6914ab8b1ae1c260a4ae7a49b6c5611b40328a735b21862567685e73255"

[[package]]
name = "serde"
version = "1.0.219"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "5f0e2c6ed6606019b4e29e69dbaba95b11854410e5347d525002456dbbb786b6"
"#;

/// An OSV `/v1/querybatch` response for the three packages above, in which the
/// second carries RUSTSEC-2020-0071 (the real `time` segfault advisory).
///
/// Batch results are deliberately minimal at OSV -- `id` and `modified` only --
/// which is why nothing here parses a severity it was not sent.
const BATCH_HIT: &str = r#"{"results":[
  {},
  {"vulns":[{"id":"RUSTSEC-2020-0071","modified":"2023-11-08T04:03:56.987Z"},
            {"id":"GHSA-wcg3-cvx6-7396","modified":"2023-11-08T04:03:56.987Z"}]},
  {"vulns":[]}
]}"#;

/// The same three packages, all clean. OSV returns an empty object per query
/// rather than omitting the entry.
const BATCH_CLEAN: &str = r#"{"results":[{},{"vulns":[]},{}]}"#;

fn packages() -> Vec<LockedPackage> {
    SupplyChainGuard::parse_lockfile(LOCKFILE).expect("the fixture lockfile parses")
}

fn ctx(work_dir: &Path) -> PrDiffContext {
    PrDiffContext {
        repo: "oyatie/anvil".to_string(),
        pr_number: 1,
        base_branch: "main".to_string(),
        base_sha: "aaa".to_string(),
        head_sha: "bbb".to_string(),
        previous_head_sha: None,
        repo_working_dir: anvil::git_manager::SubjectRoot::asserted(
            work_dir.to_path_buf(),
            anvil::git_manager::Uncloned::TestFixture,
        ),
        diff_content: "+ time = \"0.1.44\"\n".to_string(),
        changed_files: vec!["Cargo.toml".to_string()],
        is_incremental: false,
    }
}

fn assert_not_measured(status: &GateStatus, gate_id: &str, must_mention: &[&str]) {
    let GateStatus::NotMeasured {
        gate_id: id,
        reason,
    } = status
    else {
        panic!("expected {gate_id} to report NotMeasured, got {status:?}");
    };
    assert_eq!(id, gate_id, "NotMeasured must name its own gate");
    let lower = reason.to_lowercase();
    for needle in must_mention {
        assert!(
            lower.contains(&needle.to_lowercase()),
            "the reason must say what was missing; {needle:?} is absent from {reason:?}"
        );
    }
}

