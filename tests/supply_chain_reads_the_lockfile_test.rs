#[test]
fn a_rate_limited_or_failed_request_is_an_error_not_an_empty_body() {
    // 429 is the one that matters: OSV publishes no quota, so a busy runner
    // finding out by being throttled must abstain rather than certify.
    for code in ["429", "400", "500", "503"] {
        let err = osv_stream::body_of(&format!("{{\"results\":[]}}\n{code}"))
            .expect_err("a non-200 response is not a clean audit");
        assert!(
            err.contains(code),
            "the reason must name the status the runner actually got: {err}"
        );
    }
}

#[test]
fn output_carrying_no_status_code_is_an_error() {
    // curl replaced by something that is not curl, or killed before `-w` ran.
    assert!(osv_stream::body_of("").is_err());
    assert!(osv_stream::body_of("just a body, no trailing status").is_err());
}

